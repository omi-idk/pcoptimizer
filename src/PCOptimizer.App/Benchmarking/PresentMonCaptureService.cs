using System.Diagnostics;
using System.IO;
using System.Security.Cryptography;
using PCOptimizer.Benchmarking;

namespace PCOptimizer.App.Benchmarking;

internal sealed record CaptureTarget(int Id, DateTime StartTimeUtc, string Name)
{
    public override string ToString() => $"{Name} · PID {Id}";
}
internal interface IPresentMonCaptureService
{
    Task<BenchmarkCapability> CheckAsync(string executable, CancellationToken cancellationToken);
    Task<string> CaptureAsync(string executable, CaptureTarget target, int seconds, CancellationToken cancellationToken);
}

// Executes only the pinned, hash-verified console, under the same unelevated user as the GUI.
// No DLL injection, game process writes, priority changes or global ETW session termination.
internal sealed class PresentMonCaptureService(string directory) : IPresentMonCaptureService
{
    public async Task<BenchmarkCapability> CheckAsync(string executable, CancellationToken cancellationToken)
    {
        if (!OperatingSystem.IsWindows() || !Environment.Is64BitOperatingSystem)
            return new(CapabilityState.Unsupported, "La captura requiere Windows x64.");
        try
        {
            await using var file = OpenExecutable(executable);
            await VerifyAsync(file, cancellationToken);
            return new(CapabilityState.ValidationRequired, "PresentMon 2.6.0 x64 verificado por SHA-256. El acceso ETW depende de permisos y proveedores; compatibilidad con el juego pendiente de validación.");
        }
        catch (UnauthorizedAccessException) { return new(CapabilityState.PermissionRequired, "No se puede leer el ejecutable seleccionado."); }
        catch (IOException ex) { return new(CapabilityState.Unsupported, ex.Message); }
        catch (InvalidDataException ex) { return new(CapabilityState.Unsupported, ex.Message); }
    }

    private static FileStream OpenExecutable(string path)
    {
        if (!Path.IsPathFullyQualified(path) || !string.Equals(Path.GetExtension(path), ".exe", StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException("Selecciona el ejecutable oficial PresentMon-2.6.0-x64.exe.");
        return new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 65536, true);
    }
    private static async Task VerifyAsync(FileStream file, CancellationToken cancellationToken)
    {
        if (file.Length > 64 * 1024 * 1024) throw new InvalidDataException("Ejecutable mayor de 64 MiB.");
        var digest = Convert.ToHexString(await SHA256.HashDataAsync(file, cancellationToken));
        if (digest != PresentMonVersion.Sha256) throw new InvalidDataException("El SHA-256 no coincide con PresentMon 2.6.0 x64 oficial. No se ejecutará.");
    }

    public async Task<string> CaptureAsync(string executable, CaptureTarget target, int seconds, CancellationToken cancellationToken)
    {
        await using var binaryLock = OpenExecutable(executable);
        await VerifyAsync(binaryLock, cancellationToken); // The read-only handle prevents replacement during this capture on Windows.
        using var game = Process.GetProcessById(target.Id);
        if (game.HasExited || game.StartTime.ToUniversalTime() != target.StartTimeUtc)
            throw new InvalidOperationException("El proceso terminó o su PID fue reutilizado. Actualiza la lista.");
        Directory.CreateDirectory(directory);
        var sessionName = Guid.NewGuid().ToString("N");
        var output = Path.GetFullPath(Path.Combine(directory, sessionName + ".csv"));
        var start = CreateStart(executable, PresentMonVersion.CaptureArguments(target.Id, seconds, sessionName, output));
        using var process = Process.Start(start) ?? throw new IOException("No se pudo iniciar PresentMon.");
        var errors = ReadErrorsAsync(process.StandardError);
        string? cleanupFailure = null;
        var completion = await CaptureLifetime.WaitAsync(process.WaitForExitAsync, async () =>
        {
            if (!process.HasExited)
            {
                // This unique name is generated by us; never stop the default PresentMon session or another tool.
                try
                {
                    using var stop = Process.Start(CreateStart(executable, ["--session_name", sessionName, "--terminate_existing_session"]));
                    if (stop is null) throw new IOException("No se inició la solicitud de cierre ETW.");
                    var stopErrors = ReadErrorsAsync(stop.StandardError);
                    try { await stop.WaitForExitAsync().WaitAsync(TimeSpan.FromSeconds(5)); }
                    catch (TimeoutException) { if (!stop.HasExited) stop.Kill(); await stop.WaitForExitAsync(); }
                    var stopDetail = await stopErrors;
                    if (stop.ExitCode != 0) cleanupFailure = $"Código {stop.ExitCode}. {stopDetail}";
                }
                catch (Exception ex) when (ex is IOException or System.ComponentModel.Win32Exception or InvalidOperationException)
                {
                    cleanupFailure = ex.Message;
                }
                finally
                {
                    // Failure to launch the stop command must not leave our auxiliary running indefinitely.
                    try { await process.WaitForExitAsync().WaitAsync(TimeSpan.FromSeconds(5)); }
                    catch (TimeoutException) { if (!process.HasExited) process.Kill(); await process.WaitForExitAsync(); }
                }
            }
        }, TimeSpan.FromSeconds(seconds + 20), cancellationToken);
        var detail = await errors;
        if (cleanupFailure is not null)
            throw new IOException($"El auxiliar terminó, pero no se confirmó el cierre de nuestra sesión ETW {sessionName}: {cleanupFailure}. El CSV se conserva en {output}.");
        if (cancellationToken.IsCancellationRequested)
        {
            if (File.Exists(output) && new FileInfo(output).Length > 0) return output;
            throw new OperationCanceledException(cancellationToken);
        }
        if (completion == CaptureCompletion.TimedOut) throw new IOException("PresentMon superó el tiempo previsto. Se solicitó terminar solo nuestra sesión ETW.");
        if (process.ExitCode != 0) throw new IOException($"PresentMon terminó con código {process.ExitCode}. {detail} El acceso ETW puede requerir pertenecer a Performance Log Users; la app no modifica grupos ni se eleva automáticamente.");
        if (!File.Exists(output)) throw new IOException("PresentMon no generó CSV. Comprueba PID, actividad gráfica y permisos ETW.");
        return output;
    }

    private static ProcessStartInfo CreateStart(string executable, IReadOnlyList<string> arguments)
    {
        var start = new ProcessStartInfo(executable) { UseShellExecute = false, CreateNoWindow = true, RedirectStandardError = true,
            WorkingDirectory = Path.GetDirectoryName(executable)! };
        foreach (var argument in arguments) start.ArgumentList.Add(argument);
        return start;
    }
    private static async Task<string> ReadErrorsAsync(StreamReader reader)
    {
        var buffer = new char[2048]; var tail = "";
        int count;
        while ((count = await reader.ReadAsync(buffer)) != 0)
        {
            tail += new string(buffer, 0, count);
            if (tail.Length > 4096) tail = tail[^4096..];
        }
        return tail;
    }
}
